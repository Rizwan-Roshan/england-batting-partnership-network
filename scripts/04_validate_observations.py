"""Stage 4: validate observations and write the data-quality report."""
import _bootstrap  # noqa: F401
import sys

import pandas as pd

from batnet import config, ingest, tables, validate
from batnet.logutil import get_logger

log = get_logger("04_validate")


def md_table(df: pd.DataFrame) -> str:
    head = "| " + " | ".join(map(str, df.columns)) + " |\n|" + "---|" * len(df.columns)
    body = "\n".join("| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False))
    return head + "\n" + body


def main() -> int:
    P = config.PROCESSED_DIR
    meta = tables.read_csv(P / "match_metadata.csv")
    obs = tables.read_csv(P / "partnership_observations.csv")
    innings = tables.read_csv(P / "innings_summary.csv")
    warnings = tables.read_csv(P / "extraction_warnings.csv")
    audit = tables.read_csv(config.INTERIM_DIR / "file_audit.csv")

    structural = pd.DataFrame(validate.observation_checks(obs, innings), columns=["check", "passed", "detail"])
    score = pd.DataFrame([c for m in meta.to_dict("records")
                          for c in validate.scorecard_checks(ingest.load_match(config.RAW_JSON_DIR / m["filename"]),
                                                             m["match_id"], m["format"])])
    spots = validate.spot_checks(obs)
    tables.write_csv(structural, config.TABLES_DIR / "validation_structural_checks.csv")
    tables.write_csv(score, config.TABLES_DIR / "validation_scorecard_checks.csv")
    tables.write_csv(spots, config.TABLES_DIR / "validation_spot_checks.csv")

    score_summary = (score.groupby(["format", "check"])["passed"].agg(checked="size", passed="sum")
                     .reset_index())
    failed_score = score[~score["passed"]]
    q = innings[innings["qualifying"]]
    counts = pd.DataFrame({
        "matches": meta.groupby("format").size(),
        "matches_with_england_innings": q.groupby("format")["match_id"].nunique(),
        "england_innings": q.groupby("format").size(),
        "observations": obs.groupby("format").size(),
        "partnership_runs": obs.groupby("format")["partnership_runs"].sum(),
        "wicket_records": q.groupby("format")["wicket_records"].sum(),
        "deliveries": q.groupby("format")["delivery_count"].sum(),
    }).reindex(list(config.FORMATS)).reset_index()
    tables.write_csv(counts, config.TABLES_DIR / "dataset_counts.csv")

    special = innings[(innings["penalty_runs_pre"] + innings["penalty_runs_post"] > 0)
                      | innings["absent_hurt"].notna() | innings["super_over"]]
    non_dismissal = obs[obs["boundary_reason"].str.startswith(("replacement", "retirement", "unexplained"))]
    no_inn = meta[meta["n_innings_england"] == 0]

    lines = [
        "# Data-quality report", "",
        "Generated by `scripts/04_validate_observations.py`. Do not edit by hand.", "",
        "## Source files", "",
        f"- JSON files in archive: {len(audit)}; unreadable: {int(audit['exclusion_reason'].astype(str).str.startswith('unreadable').sum())}",
        f"- Included matches: {int(audit['included'].sum())}; excluded: {int((~audit['included']).sum())}",
        "", "Exclusion reasons (one per excluded file):", "",
        md_table(audit.loc[~audit["included"], "exclusion_reason"].value_counts().rename_axis("reason").reset_index(name="files")),
        "", "## Counts by format", "", md_table(counts), "",
        f"Included matches in which England never batted (abandoned / no result before England's innings): "
        f"{len(no_inn)} ({', '.join(no_inn['match_id'].astype(str))}). They stay in the match table but yield no observations.",
        "", "## Structural checks", "", md_table(structural), "",
        "## Independent scorecard checks", "",
        "Innings totals recomputed from raw deliveries (without the extractor) compared with the target and "
        "run margin recorded by Cricsheet. Matches decided with a rain-adjustment method are not checked.", "",
        md_table(score_summary), "",
        f"Failed scorecard checks: {len(failed_score)}", "",
        (md_table(failed_score) if len(failed_score) else ""), "",
        "## Spot checks against documented partnerships", "", md_table(spots), "",
        "## Extraction warnings", "",
        (md_table(warnings) if len(warnings) else "None: every pair change is explained by a wicket record, "
         "a batter replacement record or the end of the innings."), "",
        "## Partnership boundaries other than dismissals / innings end", "",
        md_table(non_dismissal[["match_id", "format", "match_date", "innings_index", "player_1_name",
                                "player_2_name", "partnership_runs", "boundary_reason"]]), "",
        "## Innings with penalty runs, absent batters or super overs", "",
        md_table(special[["match_id", "format", "innings_index", "penalty_runs_pre", "penalty_runs_post",
                          "absent_hurt", "super_over", "runs_from_deliveries"]].fillna("")), "",
        "Innings-level penalty runs are not part of any delivery and are therefore not assigned to any pair.", "",
    ]
    (config.ROOT / "docs" / "data_quality_report.md").write_text("\n".join(lines), encoding="utf-8")

    ok = bool(structural["passed"].all() and score["passed"].all() and spots["passed"].all() and len(warnings) == 0)
    log.info("structural checks passed: %d/%d", structural["passed"].sum(), len(structural))
    log.info("scorecard checks passed: %d/%d", score["passed"].sum(), len(score))
    log.info("spot checks passed: %d/%d", spots["passed"].sum(), len(spots))
    log.info("extraction warnings: %d", len(warnings))
    log.info("GATE %s", "PASSED" if ok else "FAILED - see docs/data_quality_report.md")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
